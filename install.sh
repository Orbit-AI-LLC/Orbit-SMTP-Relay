cat <<SUMMARY

$(log "Relay node ${NODE_NAME} is installed.")

  Status        : orbit-relay status
                  curl -s http://127.0.0.1:${STATUS_PORT}/status | python3 -m json.tool
  Logs          : journalctl -u ${SERVICE} -f        (the agent)
                  journalctl -u 'postfix@*' -f       (Postfix)
  Services      : systemctl status ${SERVICE} postfix
  Configuration : ${ENV_FILE}
  Update        : re-run this install command (settings and keys are remembered)
  Encryption    : inbound mail is sealed to each reader's key before it reaches
                  the server. This node's own key is ${KEY_FILE}; back it up,
                  and show its id with: orbit-relay key show

Next: point each domain's MX record at ${RELAY_HOSTNAME}. For Orbit's own
fleet, also set it as the relay hostname on Mission Control's Mail page.
SUMMARY

if (( ${#MIGRATED_VOLUMES[@]} )); then
    cat <<DOCKER
The relay no longer uses Docker. Once mail flows, remove what is left of the
old container:

  docker volume rm ${MIGRATED_VOLUMES[*]}
  docker image rm orbit-relay:local
DOCKER
fi
